export function renderTemplatePage(template, { baseUrl = null, version = '' } = {}) {
    const origin = typeof baseUrl === 'string' && baseUrl.trim() ? baseUrl.trim().replace(/\/+$/, '') : null;
    const canonical = origin ? `${origin}/templates/${encodeURIComponent(template.id)}.html` : null;
    const body = `<header class="site-head"><a href="../">RWA Sonar</a><nav><a href="./index.html">Legal templates</a><a href="../stocks.html">Stock app</a></nav></header>` +
        `<main><p class="eyebrow">Technology + legal template</p><h1>${esc(template.legalTemplate)}</h1>` +
        `<p class="lede">${esc(template.summary)}</p>` +
        `${template.underReview?.length ? `<div class="under-review-banner"><strong>Legal conclusions under review</strong><span>${template.underReview.length} priority-zero evidence change${template.underReview.length === 1 ? '' : 's'} may affect this template. Treat the marked conclusions as provisional.</span><a href="../review.html?priority=P0&issuer=${encodeURIComponent(template.issuer.slug)}">Open review queue →</a></div>` : ''}` +
        `<div class="hero-facts"><span>${esc(template.issuer.name)}</span><span>${esc(template.technologyRecipe)}</span>` +
        `<span class="status status-${escapeHtml(template.composabilityStatus)}">DeFi ${esc(template.composabilityStatus)}</span>` +
        `<span>Reviewed ${esc(fmtDate(template.reviewedAt))}</span></div>` +
        `<section><h2>What this analysis covers</h2>${assetsHtml(template)}</section>` +
        `<section><h2>Traceable conclusions</h2><p>Each conclusion carries its classification, exact supporting words, source authority, location, governing law, holder scope and review date. A document saying something is not the same as an independently observed outcome.</p>${traceabilityHtml(template)}</section>` +
        `<section><h2>Evidence confidence</h2><p>Confidence is stated per conclusion type. It is not collapsed into one score.</p>${confidenceGrid(template)}</section>` +
        `<section><h2>Complete claim chain</h2><p>Possessing the token is only the first link. Each intermediary can add a separate contract, governing law and failure dependency.</p>${chainHtml(template)}</section>` +
        `<section><h2>Jurisdiction and holder eligibility</h2>${scopeHtml(template)}</section>` +
        `<section><h2>Insolvency and enforcement</h2>${insolvencyHtml(template)}</section>` +
        `<section><h2>Corporate actions</h2>${corporateHtml(template)}</section>` +
        `<section><h2>Redemption path</h2>${redemptionHtml(template)}</section>` +
        `<section><h2>Source authority and precedence</h2>${sourceHtml(template)}</section>` +
        `<section><h2>Open questions</h2>${template.openQuestions.length
            ? `<ul>${template.openQuestions.map((question) => `<li>${esc(question)}</li>`).join('')}</ul>`
            : '<p>No open question is currently recorded.</p>'}</section>` +
        `<footer><p>This is a template-level conclusion. A named asset inherits it unless an explicit exception is recorded above.</p>` +
        `<nav><a href="./index.html">All legal templates</a><a href="../stocks.html">Compare tokenized stocks</a></nav></footer></main>`;
    return pageShell({
        title: `${template.issuer.name} legal template — RWA Sonar`,
        description: `${template.legalTemplate}: claim chain, insolvency, eligibility, redemption, corporate actions and evidence authority.`,
        canonical,
        body,
        version
    });
}

export function renderTemplateIndex(templates, { baseUrl = null, version = '' } = {}) {
    const origin = typeof baseUrl === 'string' && baseUrl.trim() ? baseUrl.trim().replace(/\/+$/, '') : null;
    const cards = templates.map((template) => `<article class="template-card"><p class="eyebrow">${esc(template.issuer.name)}</p>` +
        `<h2><a href="./${encodeURIComponent(template.id)}.html">${esc(template.legalTemplate)}</a></h2>` +
        `<p>${esc(template.summary)}</p><dl><dt>Technology</dt><dd>${esc(template.technologyRecipe)}</dd>` +
        `<dt>Inherited assets</dt><dd>${template.inheritance.count} token address${template.inheritance.count === 1 ? '' : 'es'} · ` +
        `${template.inheritance.underlyingCount} underlying${template.inheritance.underlyingCount === 1 ? '' : 's'}</dd>` +
        `<dt>Evidence</dt><dd>${template.evidenceConfidence.filter((row) => row.level !== 'unknown').length}/${template.evidenceConfidence.length} dimensions established</dd></dl>` +
        `<a class="open-template" href="./${encodeURIComponent(template.id)}.html">Open full legal analysis →</a></article>`).join('');
    const body = `<header class="site-head"><a href="../">RWA Sonar</a><nav><a href="../stocks.html">Stock app</a><a href="../whatif.html">Failure scenarios</a></nav></header>` +
        `<main><p class="eyebrow">Reusable legal architecture</p><h1>Technology + legal templates</h1>` +
        `<p class="lede">Assets inherit analysis only when both their issuer programme and observed on-chain control recipe match. This keeps one legal conclusion maintainable without pretending every token is identical.</p>` +
        `<div class="template-grid">${cards}</div>` +
        `<footer><a href="../stocks.html">Open the tokenized-stock app</a></footer></main>`;
    return pageShell({
        title: 'Tokenized-stock legal templates — RWA Sonar',
        description: 'Compare the legal and technical structures inherited by tokenized stocks on Solana.',
        canonical: origin ? `${origin}/templates/` : null,
        body,
        version
    });
}
